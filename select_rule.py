#     ・g+h の 1.15 と同じ点数に揃える値は 1.114 で、この範囲の中に入る。
#       「点数を揃える」基準と「平らな範囲の真ん中」がほぼ一致した。
#     ・点数は 3,545点 → 1,701点（17か月）。
