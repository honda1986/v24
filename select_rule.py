# 片方だけ直すと本番と検証がずれるので、__main__ の自己テストで突き合わせる。
_COMBOS = [f"{a}-{b}-{c}" for a in range(1, 7) for b in range(1, 7) if b != a
           for c in range(1, 7) if c not in (a, b)]
FIRST1 = [int(c[0]) for c in _COMBOS]      # 各組の1着号艇 (1〜6)


def pick_ana(q, p, odds, pq_min=None):
    """穴側(試験)の買い目の添字を返す。

    q     : 各組の市場確率 (120通り)
    p     : 各組のモデル確率 (g と h を入れたもの。合計1)
    odds  : 各組の締切前オッズ (120通り。fetch_odds が返す生の倍率)

    ★race_ok は呼び出し側で確かめること。帯と同じ足切りを使う。
    ★そのレースの最低オッズが8倍以上なら、この関数は空を返す（メモ §45）。
      オッズが120個そろっていない回も空を返す。
    """
    lo = ANA_PQ_MIN if pq_min is None else pq_min
    # ★本命が居ないレース（最低オッズが8倍以上の混戦）は丸ごと見送る。
    #   0以下やNoneが混ざっていても落ちないように、正の値だけで最小を取る。
    # ★長さも見る。ここを見ないと odds が短いときに IndexError、
    #   空のときに min() の ValueError で落ちる（呼び出し側が守っているので
    #   いまは到達しないが、docstring の約束を実装で担保しておく）
    if len(odds) != len(FIRST1):
        return []
    valid = [float(o) for o in odds if o is not None and float(o) > 0]
    if len(valid) != len(odds) or min(valid) >= ANA_RACE_MIN_ODDS:
        return []
    out = []
    for i, one in enumerate(FIRST1):
        if one == 1:                      # 1着が1号艇の組は買わない
            continue
        qi = q[i]
        if qi is None or qi <= 0:
            continue
        o = odds[i]
        if o is None or not (ANA_ODDS_LO <= float(o) < ANA_ODDS_HI):
            continue
        if p[i] / qi > lo:
            out.append(i)
    return out


def race_ok(jcd, wave_cm, wind_ms):
    """このレースを買ってよいか。波高・風速は直前情報の値を渡すこと。

    値が取れなかった場合は False(見送り)を返す。
    無条件に買うより、取れないレースは見送るほうが安全。
    """
    if int(jcd) in TANSUI:
        return False
    if wave_cm is None or wind_ms is None:
        return False
    w, v = float(wave_cm), float(wind_ms)
    # ★下限も見る（2026-09-13 追加）。検証データでは欠損が -1 / -99 で入って
    #   おり、上限しか見ないとそれが「波-1cm・風-99m」として買い対象に
    #   なってしまう。本番の直前情報は None で来る想定だが、パーサが
    #   変わって負値が来たときに黙って買うほうが危ない。
    if w < 0 or v < 0:
        return False
    return w < WAVE_MAX and v < WIND_MAX


def pick(q, p, pq_min=None):
    """買う組の添字を返す。

    q : 各組の市場確率 (3連単120通り。1/オッズ を合計1に正規化したもの)
    p : 各組のモデル確率 (同じ並び。合計1に正規化しておくこと)
    """
    out = []
    for i, (qi, pi) in enumerate(zip(q, p)):
        if qi <= 0:
            continue
        if Q_LO <= qi < Q_HI and pi / qi > (PQ_MIN if pq_min is None else pq_min):
            out.append(i)
    return out


def decide(jcd, wave_cm, wind_ms, q, p, pq_min=None):
    """1レース分の判定。買わないなら空リスト。買うなら組の添字のリスト。"""
    if not race_ok(jcd, wave_cm, wind_ms):
        return []
    return pick(q, p, pq_min)


