"""select_rule.py -- 採用したレース選別ルール (2026-08-21 確定)

本番に入れるのはこの1ファイルだけでよい。判定はすべてレース前に確定する情報で行う。

┌ 採用したルール ────────────────────────────────────────────┐
│  1. 水質      淡水の9場では買わない                                    │
│  2. 水面      波高 0〜2cm かつ 風速 4m未満 のレースだけ買う              │
│  3. 帯        3連単の組のうち 市場確率 q が 0.12 以上 0.25 未満のものだけ  │
│  4. モデル    MF(市場+ファンダ)由来の p/q が 1.05 を超える組だけ          │
│  5. 賭け方    対象の組を100円ずつ均等に買う                             │
└──────────────────────────────────────────────────────────┘

■ 根拠 (詳細は引き継ぎメモ §11)
  1+2 はモデルを使わないので学習期間でも検証できる。5期間すべてで再現した。
      2024/3-2025/3(未使用) +3.8pt / 2025/4 +2.6pt / 2026/2-3 +2.8pt
      2025/5-2026/1 +6.5pt / 2026/4- +5.5pt
      1号艇1着率 54.5% → 59.2% と物理の裏づけもある
      24場から1場ずつ抜いても差は +3.2〜+4.3pt。どの単一場にも依存しない
  3+4 と組み合わせた成績 (20250401以降、11,373組 → 4,487組)
      実測/市場 1.194 → 1.285   回収率 88.9% → 96.0% ±3.0
      差 +7.1pt  95%区間 +2.7〜+11.5pt   100%を超える確率 8%

■ 承知しておくこと
  ・なぜ淡水が悪いのかは分かっていない。1号艇1着率では説明できない
    (芦屋は1号艇1着率が全場最高 59.6% なのに回収率は最低 78.4%)
    機序が説明できない効果は将来消える可能性が相対的に高い
  ・4 の p/q は確定オッズで検証した数字。実運用の締切前オッズでは目減りする
  ・100%は超えていない。504日で1日6.6レース買って収支 -18,040円 の水準

■ ★実装上いちばん大事な注意
  検証は Kファイル(レース後の記録値)の波高・風速で行った。
  実運用では predict.py の fetch_beforeinfo() が返す直前情報の値を使うこと。
  導入前に、直前情報の波高・風速の分布が Kファイルと一致するか必ず確かめる。
  ずれていたらしきい値(3cm / 4m)を合わせ直す必要がある。

■ 潮・天候・場は採用しない (メモ §10 §11 §12)
  潮の干満差   大潮×波高の相関が全群で実質ゼロ。痕跡が無い
  天候(晴)     1号艇1着率が 56.9%→57.2% しか動かず、95%区間が0をまたぐ
  場ごとの選別  期間間の相関 +0.004 / +0.044 / -0.186。乱数
  静水面/難水面 1号艇1着率は動くが回収率は同じ。市場が織り込み済み
"""

# 淡水の9場。ここでは買わない
TANSUI = {1, 2, 5, 10, 11, 12, 13, 21, 23}
# 参考: 汽水 {3, 6, 7, 9, 22} / 海水 {4, 8, 14, 15, 16, 17, 18, 19, 20, 24}

WAVE_MAX = 3      # 波高がこの値未満(cm)。つまり 0,1,2cm
WIND_MAX = 4      # 風速がこの値未満(m)。つまり 0〜3m
Q_LO, Q_HI = 0.12, 0.25    # 市場確率の帯
PQ_MIN = 1.05              # モデル確率 / 市場確率


def race_ok(jcd, wave_cm, wind_ms):
    """このレースを買ってよいか。波高・風速は直前情報の値を渡すこと。

    値が取れなかった場合は False(見送り)を返す。
    無条件に買うより、取れないレースは見送るほうが安全。
    """
    if int(jcd) in TANSUI:
        return False
    if wave_cm is None or wind_ms is None:
        return False
    return float(wave_cm) < WAVE_MAX and float(wind_ms) < WIND_MAX


def pick(q, p):
    """買う組の添字を返す。

    q : 各組の市場確率 (3連単120通り。1/オッズ を合計1に正規化したもの)
    p : 各組のモデル確率 (同じ並び。合計1に正規化しておくこと)
    """
    out = []
    for i, (qi, pi) in enumerate(zip(q, p)):
        if qi <= 0:
            continue
        if Q_LO <= qi < Q_HI and pi / qi > PQ_MIN:
            out.append(i)
    return out


def decide(jcd, wave_cm, wind_ms, q, p):
    """1レース分の判定。買わないなら空リスト。買うなら組の添字のリスト。"""
    if not race_ok(jcd, wave_cm, wind_ms):
        return []
    return pick(q, p)


if __name__ == "__main__":
    # 自己テスト。実際のオッズに近い偏った分布で確かめる
    import random
    random.seed(0)
    # 本命に厚い分布を作る(3連単の実際の形に近づける)
    q = sorted((random.paretovariate(1.3) for _ in range(120)), reverse=True)
    s_ = sum(q); q = [x / s_ for x in q]
    p = [x * random.uniform(0.92, 1.20) for x in q]
    s_ = sum(p); p = [x / s_ for x in p]
    inband = sum(1 for x in q if 0.12 <= x < 0.25)
    print(f"帯 q0.12〜0.25 に入る組: {inband}点")
    print("淡水(戸田=2)は必ず見送り :", decide(2, 1, 2, q, p) == [])
    print("波6cmは見送り            :", decide(24, 6, 2, q, p) == [])
    print("風5mは見送り             :", decide(24, 1, 5, q, p) == [])
    print("気象が取れなければ見送り   :", decide(24, None, 2, q, p) == [])
    sel = decide(24, 1, 2, q, p)
    print(f"大村・波1cm・風2m の買い目: {len(sel)}点  "
          f"(帯{inband}点のうち p/q>1.05 を満たしたもの)")
    print("参考: 実データでは1レースあたり 帯 約2.7点 → 買い目 平均1.3点")
