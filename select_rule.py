# -*- coding: utf-8 -*-
"""select_rule.py -- 採用したレース選別ルール (2026-08-21 確定)

本番に入れるのはこの1ファイルだけでよい。判定はすべてレース前に確定する情報で行う。

┌ 採用したルール ────────────────────────────────────────────┐
│  1. 水質      淡水の9場では買わない                                    │
│  2. 水面      波高 0〜2cm かつ 風速 4m未満 のレースだけ買う              │
│  3. 帯        3連単の組のうち 市場確率 q が 0.12 以上 0.25 未満のものだけ  │
│  4. モデル    MF(市場+ファンダ)由来の p/q が 1.05 を超える組だけ          │
│  5. 賭け方    対象の組を100円ずつ均等に買う                             │
└──────────────────────────────────────────────────────────┘

■ 根拠 (詳細は引き継ぎメモ §11)
  1+2 はモデルを使わないので学習期間でも検証できる。5期間すべてで再現した。
      2024/3-2025/3(未使用) +3.8pt / 2025/4 +2.6pt / 2026/2-3 +2.8pt
      2025/5-2026/1 +6.5pt / 2026/4- +5.5pt
      1号艇1着率 54.5% → 59.2% と物理の裏づけもある
      24場から1場ずつ抜いても差は +3.2〜+4.3pt。どの単一場にも依存しない
  3+4 と組み合わせた成績 (20250401以降、11,373組 → 4,487組)
      実測/市場 1.194 → 1.285   回収率 88.9% → 96.0% ±3.0
      差 +7.1pt  95%区間 +2.7〜+11.5pt   100%を超える確率 8%

■ 承知しておくこと
  ・なぜ淡水が悪いのかは分かっていない。1号艇1着率では説明できない
    (芦屋は1号艇1着率が全場最高 59.6% なのに回収率は最低 78.4%)
    機序が説明できない効果は将来消える可能性が相対的に高い
  ・4 の p/q は確定オッズで検証した数字。実運用の締切前オッズでは目減りする
  ・100%は超えていない。504日で1日6.6レース買って収支 -18,040円 の水準

■ ★実装上いちばん大事な注意
  検証は Kファイル(レース後の記録値)の波高・風速で行った。
  実運用では predict.py の fetch_beforeinfo() が返す直前情報の値を使うこと。
  導入前に、直前情報の波高・風速の分布が Kファイルと一致するか必ず確かめる。
  ずれていたらしきい値(3cm / 4m)を合わせ直す必要がある。

■ 潮・天候・場は採用しない (メモ §10 §11 §12)
  潮の干満差   大潮×波高の相関が全群で実質ゼロ。痕跡が無い
  天候(晴)     1号艇1着率が 56.9%→57.2% しか動かず、95%区間が0をまたぐ
  場ごとの選別  期間間の相関 +0.004 / +0.044 / -0.186。乱数
  静水面/難水面 1号艇1着率は動くが回収率は同じ。市場が織り込み済み
"""

# 淡水の9場。ここでは買わない
TANSUI = {1, 2, 5, 10, 11, 12, 13, 21, 23}
# 参考: 汽水 {3, 6, 7, 9, 22} / 海水 {4, 8, 14, 15, 16, 17, 18, 19, 20, 24}

WAVE_MAX = 3      # 波高がこの値未満(cm)。つまり 0,1,2cm
WIND_MAX = 4      # 風速がこの値未満(m)。つまり 0〜3m
Q_LO, Q_HI = 0.12, 0.25    # 市場確率の帯
PQ_MIN = 1.05              # モデル確率 / 市場確率
# ★2着の補正 g を使うときのしきい値（メモ §30）。
#   g は p/q を中央値で約2%押し上げるので、1.05 のままだと買い目が6割増える。
#   1.08 は「回収率が最大になる点」ではなく、**買う点数が補正前と同じになる点**。
#   探索で選ぶと §3 のノイズ拾いになるので、点数を揃えるという基準で決めた。
PQ_MIN_G = 1.078          # 本番の bt.py が出した「点数を揃える値」1.0778
# ★2着＋3着の両方を使うときのしきい値（メモ §35）。同じく「点数を揃える」基準。
#   本番の bt.py が出した値 1.0971 に合わせた（代役の 1.1009 ではなく）。
#   ★回収率が最大になる点を探してはいけない。点数を揃えるだけ。
PQ_MIN_GH = 1.097


# ---------------------------------------------------------------- 穴側(試験)
# ★メモ §41 (2026-09-13)。これは **本採用ではない**。
#   帯の買い目とは別勘定で持ち、通知も分け、回収率も分けて数える。
#
#   条件: 1着が1号艇でない × 締切前オッズ 8.0〜15.0倍 × p/q > 1.097
#
#   検証 (20250401-20260818 / 淡水以外・波<3cm・風<4m / g と h を入れた p)
#     992レース 1,269点 (平均1.28点/レース) 的中131レース
#     回収率 122.5% ±10.0   実測/市場 1.60   3期 127% / 121% / 119%
#     対照: 同じオッズ帯で1着=1号艇 88.2% / 選別なし 84.9% / 淡水 69.9%
#     探索込みの順列検定 p=0.015 (そのマス単独なら 0.0007)
#
#   ★承知しておくこと
#     ・**なぜそこだけ効くのか説明できていない。** 数の少なさより、
#       機序が無いことのほうが弱点。説明のつかない効果は先に消える。
#     ・g と h の両方が入った p でしか測っていない。片方でも無ければ使わない。
#     ・オッズ 8〜15 は「確定オッズ」で測った窓。本番は締切前オッズで判定する。
#       境界付近の組は入ったり出たりする。そのぶん検証値より下がりうる。
#     ・窓が繊細。7〜18倍に広げるだけで 104%、6〜25倍で 100% まで落ちる。
ANA_ODDS_LO = 8.0
ANA_ODDS_HI = 15.0
ANA_PQ_MIN = 1.097        # PQ_MIN_GH と同じ値。ここで選び直してはいない

# 3連単120通りの並びは features.COMBOS と同じ構成で作る（メモ §15）。
# 片方だけ直すと本番と検証がずれるので、__main__ の自己テストで突き合わせる。
_COMBOS = [f"{a}-{b}-{c}" for a in range(1, 7) for b in range(1, 7) if b != a
           for c in range(1, 7) if c not in (a, b)]
FIRST1 = [int(c[0]) for c in _COMBOS]      # 各組の1着号艇 (1〜6)


def pick_ana(q, p, odds, pq_min=None):
    """穴側(試験)の買い目の添字を返す。

    q     : 各組の市場確率 (120通り)
    p     : 各組のモデル確率 (g と h を入れたもの。合計1)
    odds  : 各組の締切前オッズ (120通り。fetch_odds が返す生の倍率)

    ★race_ok は呼び出し側で確かめること。帯と同じ足切りを使う。
    """
    lo = ANA_PQ_MIN if pq_min is None else pq_min
    out = []
    for i, one in enumerate(FIRST1):
        if one == 1:                      # 1着が1号艇の組は買わない
            continue
        qi = q[i]
        if qi is None or qi <= 0:
            continue
        o = odds[i]
        if o is None or not (ANA_ODDS_LO <= float(o) < ANA_ODDS_HI):
            continue
        if p[i] / qi > lo:
            out.append(i)
    return out


def race_ok(jcd, wave_cm, wind_ms):
    """このレースを買ってよいか。波高・風速は直前情報の値を渡すこと。

    値が取れなかった場合は False(見送り)を返す。
    無条件に買うより、取れないレースは見送るほうが安全。
    """
    if int(jcd) in TANSUI:
        return False
    if wave_cm is None or wind_ms is None:
        return False
    w, v = float(wave_cm), float(wind_ms)
    # ★下限も見る（2026-09-13 追加）。検証データでは欠損が -1 / -99 で入って
    #   おり、上限しか見ないとそれが「波-1cm・風-99m」として買い対象に
    #   なってしまう。本番の直前情報は None で来る想定だが、パーサが
    #   変わって負値が来たときに黙って買うほうが危ない。
    if w < 0 or v < 0:
        return False
    return w < WAVE_MAX and v < WIND_MAX


def pick(q, p, pq_min=None):
    """買う組の添字を返す。

    q : 各組の市場確率 (3連単120通り。1/オッズ を合計1に正規化したもの)
    p : 各組のモデル確率 (同じ並び。合計1に正規化しておくこと)
    """
    out = []
    for i, (qi, pi) in enumerate(zip(q, p)):
        if qi <= 0:
            continue
        if Q_LO <= qi < Q_HI and pi / qi > (PQ_MIN if pq_min is None else pq_min):
            out.append(i)
    return out


def decide(jcd, wave_cm, wind_ms, q, p, pq_min=None):
    """1レース分の判定。買わないなら空リスト。買うなら組の添字のリスト。"""
    if not race_ok(jcd, wave_cm, wind_ms):
        return []
    return pick(q, p, pq_min)


