#     ・切り落とす側（1.097 < p/q <= 1.15）は両期間とも100%未満
#       （探索 97.1% / 独立 90.1%）。捨てる向きが正しい。
#     ・独立期間で回収の大きい的中を上位10本抜いても 111.8%→約105%。
#       少数の的中に乗った数字ではない。17か月中12か月が100%超。
#     ・点数は 3,541点 → 1,508点（17か月・約6割減）。
#       買った日あたり 7.3点 → 3.5点。通知はおよそ半分になる。
#
#   ★これは「回収率が最大になる点を探した」値ではない。1.13〜1.16 はどれも
#     両期間で100%を超える平らな範囲で、その真ん中を取っただけ。
#     1.17 以上・1.12 以下は片方の期間で100%を割る。幅で選んでいる。
#   ★波・風の足切りは「効いている」と確認できなかった（band_howto.md §10-§11）。
#     外しても数字は変わらないが、外す積極的な理由も無いので現状維持とした。
#     残す理由は「効くから」ではなく「外す理由も無いから」。
PQ_MIN_GH = 1.15

