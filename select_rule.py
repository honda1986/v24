#     2025/05〜2026/01 の10か月（＝このしきい値を決めるのに使っていない期間）と、
#     2026/02〜09（決めるのに使った期間）の両方で測り直した。
#       p/q>  探索2026/02-09   独立2025/05-2026/01   通し
#       1.097    99.2%            99.3%              99.3%  [93,106] P(>100%)=0.43
