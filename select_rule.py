    print("\n穴側(試験)")
    print("  COMBOS の並びは features.py と一致")
    # ★狙った組だけが選ばれるかを、手で作った盤面で確かめる。
    #   1着が2号艇の組の添字は 20〜39（COMBOS の並び）
